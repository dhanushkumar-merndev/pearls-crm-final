/**
 * Builds the pgTAP test that runs packages/shared/test-vectors/gst.json against the SQL
 * line maths (private.compute_line), so the screen preview and the saved bill can never
 * disagree. `pnpm vectors` writes it; a unit test fails if it is out of date.
 */
import { readFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
export const VECTORS_PATH = resolve(here, "../test-vectors/gst.json");
export const SQL_TEST_PATH = resolve(here, "../../../supabase/tests/database/07_gst_vectors.test.sql");

interface Line {
  name: string;
  input: { ratePaise: number; qtyMilli: number; discountType: string; discountValue: number; gstRateBp: number; taxInclusive: boolean };
  expect?: Record<string, number>;
  error?: string;
}

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const call = (i: Line["input"]) =>
  `private.compute_line(${i.ratePaise}, ${i.qtyMilli / 1000}, ${q(i.discountType)}::public.discount_type, ${i.discountValue}, ${i.gstRateBp}, ${i.taxInclusive})`;

export function buildVectorSql(): string {
  const { lines, errors } = JSON.parse(readFileSync(VECTORS_PATH, "utf8")) as { lines: Line[]; errors: Line[] };
  const out = [
    "-- GENERATED by `pnpm vectors` from packages/shared/test-vectors/gst.json — do not edit by hand.",
    "-- The SQL bill-line maths must give exactly the same answers as packages/shared/src/gst.ts.",
    "begin;",
    "create extension if not exists pgtap with schema extensions;",
    "set search_path = public, extensions;",
    "",
    `select plan(${lines.length + errors.length});`,
    "",
  ];
  for (const v of lines) {
    const e = v.expect!;
    out.push(
      `select is((select row(gross, discount, taxable, tax, cgst, sgst, total)::text from ${call(v.input)}),`,
      `  ${q(`(${e.grossPaise},${e.discountPaise},${e.taxablePaise},${e.taxPaise},${e.cgstPaise},${e.sgstPaise},${e.totalPaise})`)}, ${q(v.name)});`,
    );
  }
  for (const v of errors) {
    out.push(`select throws_ok(${q(`select * from ${call(v.input)}`)}, 'P0001', ${q(v.error!)}, ${q(v.name)});`);
  }
  out.push("", "select * from finish();", "rollback;", "");
  return out.join("\n");
}

export const PLACEHOLDER_VECTORS_PATH = resolve(here, "../test-vectors/placeholders.json");
export const PLACEHOLDER_SQL_TEST_PATH = resolve(here, "../../../supabase/tests/database/12_placeholder_vectors.test.sql");

interface PlaceholderCase {
  name: string;
  text: string;
  vars: Record<string, string>;
  expect: string;
  leftover: string[];
}

/** pgTAP for private.render_placeholders / private.leftover_placeholders from placeholders.json. */
export function buildPlaceholderSql(): string {
  const { cases } = JSON.parse(readFileSync(PLACEHOLDER_VECTORS_PATH, "utf8")) as { cases: PlaceholderCase[] };
  const out = [
    "-- GENERATED by `pnpm vectors` from packages/shared/test-vectors/placeholders.json — do not edit by hand.",
    "-- The SQL placeholder filling must give exactly the same text as packages/shared/src/placeholders.ts.",
    "begin;",
    "create extension if not exists pgtap with schema extensions;",
    "set search_path = public, extensions;",
    "",
    `select plan(${cases.length * 2});`,
    "",
  ];
  for (const c of cases) {
    const render = `private.render_placeholders(${q(c.text)}, ${q(JSON.stringify(c.vars))}::jsonb)`;
    const left = [...c.leftover].sort();
    out.push(
      `select is(${render}, ${q(c.expect)}, ${q(c.name)});`,
      `select is((select coalesce(array_agg(x order by x collate "C"), '{}') from unnest(private.leftover_placeholders(jsonb_build_object('t', ${render}))) x),`,
      `  ${q(`{${left.map((x) => `"${x}"`).join(",")}}`)}::text[], ${q(`${c.name}: leftovers`)});`,
    );
  }
  out.push("", "select * from finish();", "rollback;", "");
  return out.join("\n");
}
