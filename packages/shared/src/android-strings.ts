/**
 * Builds the Android app's error messages from the web app's translations, so both apps
 * say the same thing for the same RPC error code. Used by scripts/gen-tokens.ts and by
 * tests (which fail if the committed Android files are out of date).
 *   web/messages/en.json "errors.<code>"  →  android/core/ui/…/res/values/errors.xml
 *   ERROR_CODES (errors.ts)               →  android/core/ui/…/errors/ErrorStrings.kt
 */
import { ERROR_CODES } from "./errors";

const HEADER = "GENERATED by packages/shared/scripts/gen-tokens.ts from web/messages/en.json — do not edit";

/** Every code the apps translate: the stable RPC codes plus the "unknown" fallback. */
export const ANDROID_ERROR_KEYS: readonly string[] = [...ERROR_CODES, "unknown"];

/**
 * Removes ICU MessageFormat quoting: `''` is one apostrophe, and an apostrophe before a
 * `{`, `}`, `#` or `|` starts literal text up to the next lone apostrophe. Messages with
 * real ICU arguments are refused (Android error strings take no arguments).
 */
export function icuToPlain(message: string): string {
  let out = "";
  for (let i = 0; i < message.length; i++) {
    const ch = message[i]!;
    if (ch === "'") {
      if (message[i + 1] === "'") {
        out += "'";
        i++;
        continue;
      }
      if ("{}#|".includes(message[i + 1] ?? "")) {
        const end = message.indexOf("'", i + 1);
        const stop = end === -1 ? message.length : end;
        out += message.slice(i + 1, stop);
        i = stop;
        continue;
      }
      out += ch;
      continue;
    }
    if (ch === "{" || ch === "}") throw new Error(`ICU argument in an error message is not supported: ${message}`);
    out += ch;
  }
  return out;
}

/** Escapes text for an Android `<string>` resource. */
export function androidEscape(text: string): string {
  let out = text
    .replace(/\\/g, "\\\\")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/'/g, "\\'")
    .replace(/"/g, '\\"')
    .replace(/\n/g, "\\n");
  if (out.startsWith("@") || out.startsWith("?")) out = `\\${out}`;
  return out;
}

function errorMessages(messages: { errors?: Record<string, string> }): [string, string][] {
  const errors = messages.errors ?? {};
  return ANDROID_ERROR_KEYS.map((code) => {
    const text = errors[code];
    if (!text) throw new Error(`web/messages/en.json has no "errors.${code}"`);
    return [code, icuToPlain(text)];
  });
}

export function buildAndroidErrorsXml(messages: { errors?: Record<string, string> }): string {
  const lines = errorMessages(messages).map(([code, text]) => {
    // A "%" would make Android treat the text as a format string.
    const formatted = text.includes("%") ? ' formatted="false"' : "";
    return `    <string name="error_${code}"${formatted}>${androidEscape(text)}</string>`;
  });
  return `<?xml version="1.0" encoding="utf-8"?>\n<!-- ${HEADER} -->\n<resources>\n${lines.join("\n")}\n</resources>\n`;
}

export function buildAndroidErrorsKotlin(): string {
  const entries = ANDROID_ERROR_KEYS.map((code) => `    "${code}" to R.string.error_${code},`).join("\n");
  return `// ${HEADER}
package com.pearl.crm.core.ui.errors

import com.pearl.crm.core.ui.R

/** Stable RPC error code → its message (same wording as the web app). */
internal val ERROR_STRINGS: Map<String, Int> = mapOf(
${entries}
)
`;
}
