/**
 * Builds platform colour files from tokens.json. Used by scripts/gen-tokens.ts
 * and by tests (which fail if the committed web/app/tokens.css is out of date).
 */
import { tokens, type ThemeMode } from "./tokens";

const HEADER = "GENERATED by packages/shared/scripts/gen-tokens.ts from tokens.json — do not edit";

function cssVars(mode: ThemeMode): string[] {
  const c = tokens.color[mode];
  const ch = tokens.chart[mode];
  const vars: Record<string, string> = {
    background: c.page,
    foreground: c.text,
    card: c.page,
    "card-foreground": c.text,
    popover: c.raised,
    "popover-foreground": c.text,
    "popover-accent": c.raisedHover,
    primary: c.primary,
    "primary-foreground": c.primaryText,
    secondary: c.raised,
    "secondary-foreground": c.text,
    muted: c.hover,
    "muted-foreground": c.textMuted,
    accent: c.hover,
    "accent-foreground": c.text,
    destructive: c.danger,
    "destructive-foreground": c.dangerText,
    border: c.border,
    input: c.borderStrong,
    ring: c.focus,
    overlay: c.overlay,
    "text-secondary": c.textSecondary,
    link: c.link,
    "good-text": c.goodText,
    "bad-text": c.badText,
    sidebar: c.sidebar,
    "sidebar-foreground": c.text,
    "sidebar-accent": mode === "dark" ? c.page : c.hover,
    "sidebar-accent-foreground": c.text,
    "sidebar-border": c.border,
    "chart-surface": ch.surface,
    "chart-grid": ch.grid,
    "chart-axis": ch.axis,
    "chart-label": ch.label,
    "chart-emphasis-gray": ch.emphasisGray,
  };
  ch.series.forEach((hex, i) => (vars[`chart-${i + 1}`] = hex));
  for (const [name, hex] of Object.entries(tokens.status)) vars[`status-${name}`] = hex;
  return Object.entries(vars).map(([k, v]) => `  --${k}: ${v};`);
}

const radius = Object.entries(tokens.radius).map(([k, v]) => `  --pearl-radius-${k}: ${v};`);

export const buildCss = (): string => `/* ${HEADER} */
:root,
.light {
  color-scheme: light;
${cssVars("light").join("\n")}
${radius.join("\n")}
  --font-base-size: ${tokens.font.baseSizePx}px;
}

.dark {
  color-scheme: dark;
${cssVars("dark").join("\n")}
}
`;

function kotlinColor(value: string): string {
  const hex = /^#([0-9a-f]{6})$/i.exec(value);
  if (hex) return `Color(0xFF${hex[1]!.toUpperCase()})`;
  const rgba = /^rgba\((\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\)$/.exec(value);
  if (!rgba) throw new Error(`Unsupported colour ${value}`);
  const [, r, g, b, a] = rgba;
  const to2 = (n: number) => n.toString(16).padStart(2, "0").toUpperCase();
  return `Color(0x${to2(Math.round(Number(a) * 255))}${to2(Number(r))}${to2(Number(g))}${to2(Number(b))})`;
}

const pascal = (s: string) => s.charAt(0).toUpperCase() + s.slice(1);

function kotlinObject(mode: ThemeMode): string {
  const lines = Object.entries(tokens.color[mode]).map(
    ([k, v]) => `        val ${pascal(k)} = ${kotlinColor(v)}`,
  );
  const series = tokens.chart[mode].series.map(kotlinColor).join(", ");
  lines.push(`        val ChartSeries = listOf(${series})`);
  return `    object ${pascal(mode)} {\n${lines.join("\n")}\n    }`;
}

const status = Object.entries(tokens.status)
  .map(([k, v]) => `        val ${pascal(k)} = ${kotlinColor(v)}`)
  .join("\n");

export const buildKotlin = (): string => `// ${HEADER}
package com.pearl.crm.core.ui.theme

import androidx.compose.ui.graphics.Color

object PearlColors {
${kotlinObject("dark")}
${kotlinObject("light")}
    object Status {
${status}
    }
}
`;

