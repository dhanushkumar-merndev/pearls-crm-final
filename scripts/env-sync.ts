/**
 * Copies keys from the root .env to where each one is needed (pnpm env:sync):
 *   web/.env.local           only the keys the browser app may see
 *   supabase/functions/.env  Edge Function secrets
 * Deploy keys stay in the root .env. Values are never printed.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

const WEB_KEYS = [
  "NEXT_PUBLIC_SUPABASE_URL",
  "NEXT_PUBLIC_SUPABASE_ANON_KEY",
  "NEXT_PUBLIC_TURNSTILE_SITE_KEY",
  "CRON_SECRET",
];

const FUNCTION_KEYS = [
  "STORAGE_ENDPOINT",
  "STORAGE_REGION",
  "STORAGE_BUCKET",
  "STORAGE_ACCESS_KEY_ID",
  "STORAGE_SECRET_ACCESS_KEY",
  "STORAGE_PATH_STYLE",
  "WEB_ORIGIN",
  "TURNSTILE_SECRET_KEY",
  "BREVO_API_KEY",
  "META_APP_ID",
  "META_APP_SECRET",
  "META_PAGE_ID",
  "META_PAGE_ACCESS_TOKEN",
  "META_WEBHOOK_VERIFY_TOKEN",
  "WHATSAPP_WABA_ID",
  "WHATSAPP_PHONE_NUMBER_ID",
  "WHATSAPP_ACCESS_TOKEN",
  "WHATSAPP_APP_SECRET",
  "WHATSAPP_WEBHOOK_VERIFY_TOKEN",
  "FCM_PROJECT_ID",
  "FCM_SERVICE_ACCOUNT_JSON",
  "ORS_API_KEY",
];

export function parseEnv(text: string): Map<string, string> {
  const values = new Map<string, string>();
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim().replace(/^export\s+/, "");
    if (!line || line.startsWith("#")) continue;
    const eq = line.indexOf("=");
    if (eq < 1) continue;
    const key = line.slice(0, eq).trim();
    let value = line.slice(eq + 1).trim();
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    values.set(key, value);
  }
  return values;
}

/** Refuse to put a Supabase service-role/secret key into the browser app. */
export function looksLikeServerKey(value: string): boolean {
  if (value.startsWith("sb_secret_")) return true;
  const payload = value.split(".")[1];
  if (!payload) return false;
  try {
    const claims = JSON.parse(Buffer.from(payload, "base64url").toString("utf8")) as { role?: string };
    return claims.role === "service_role";
  } catch {
    return false;
  }
}

/** Single quotes are literal in dotenv (no \n or $ expansion), so JSON like FCM_SERVICE_ACCOUNT_JSON survives. */
export function formatValue(value: string): string {
  if (!/[\s#"'$\\]/.test(value)) return value;
  return value.includes("'") ? JSON.stringify(value) : `'${value}'`;
}

function render(target: string, keys: string[], values: Map<string, string>): string {
  const lines = [
    `# GENERATED by \`pnpm env:sync\` from the root .env — edit the root .env instead.`,
    `# Target: ${target}`,
    "",
  ];
  for (const key of keys) lines.push(`${key}=${formatValue(values.get(key) ?? "")}`);
  return lines.join("\n") + "\n";
}

function main() {
  const envPath = resolve(root, ".env");
  if (!existsSync(envPath)) {
    console.error("✖ No .env file yet. Copy .env.example to .env first:\n    cp .env.example .env");
    process.exit(1);
  }
  const values = parseEnv(readFileSync(envPath, "utf8"));

  for (const key of WEB_KEYS) {
    if (looksLikeServerKey(values.get(key) ?? "")) {
      console.error(`✖ ${key} contains a SERVER (service_role / secret) key. Use the anon / publishable key. Nothing was written.`);
      process.exit(1);
    }
  }

  const targets = [
    { path: "web/.env.local", keys: WEB_KEYS },
    { path: "supabase/functions/.env", keys: FUNCTION_KEYS },
  ];
  for (const { path, keys } of targets) {
    writeFileSync(resolve(root, path), render(path, keys, values));
    const filled = keys.filter((k) => values.get(k));
    const empty = keys.filter((k) => !values.get(k));
    console.log(`✔ ${path}: ${filled.length} of ${keys.length} keys filled`);
    if (empty.length) console.log(`    still empty (fine until their phase): ${empty.join(", ")}`);
  }

  const known = new Set([...WEB_KEYS, ...FUNCTION_KEYS]);
  const deployOnly = [...values.keys()].filter((k) => !known.has(k));
  if (deployOnly.length) console.log(`• kept in .env only (deploy/email/scripts): ${deployOnly.join(", ")}`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
