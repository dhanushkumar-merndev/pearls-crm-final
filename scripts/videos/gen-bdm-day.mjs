const R = 6371000;
const rad = (d) => (d * Math.PI) / 180;
function dist([a, b], [c, d]) {
  const x = Math.sin(rad(c - a) / 2) ** 2 + Math.cos(rad(a)) * Math.cos(rad(c)) * Math.sin(rad(d - b) / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(x));
}
function encode(points) {
  let out = "", pl = 0, pg = 0;
  const enc = (v) => {
    v = v < 0 ? ~(v << 1) : v << 1;
    let s = "";
    while (v >= 0x20) (s += String.fromCharCode((0x20 | (v & 0x1f)) + 63)), (v >>= 5);
    return s + String.fromCharCode(v + 63);
  };
  for (const [lat, lng] of points) {
    const a = Math.round(lat * 1e5), b = Math.round(lng * 1e5);
    out += enc(a - pl) + enc(b - pg);
    (pl = a), (pg = b);
  }
  return out;
}
const mins = (hhmm) => hhmm.split(":").map(Number).reduce((h, m) => h * 60 + m);

// Every leg: a point about every 150 m, with a little GPS wobble, times spread evenly.
let seq = 0;
const chunks = [];
for (const leg of LEGS) {
  const pts = [];
  for (let i = 0; i + 1 < leg.pts.length; i++) {
    const [a, b] = [leg.pts[i], leg.pts[i + 1]];
    const n = Math.max(1, Math.round(dist(a, b) / 150));
    for (let k = 0; k < n; k++) {
      const w = ((i * 7 + k * 13) % 5) - 2;
      pts.push([a[0] + ((b[0] - a[0]) * k) / n + w * 0.00002, a[1] + ((b[1] - a[1]) * k) / n - w * 0.00002]);
    }
  }
  pts.push(leg.pts.at(-1));
  const t0 = mins(leg.from) * 60, t1 = mins(leg.to) * 60;
  const times = pts.map((_, i) => Math.round(t0 + ((t1 - t0) * i) / (pts.length - 1)));
  // Chunks of about five minutes, each joined to the last point of the one before.
  let start = 0;
  while (start < pts.length - 1) {
    let end = start;
    while (end < pts.length - 1 && times[end + 1] - times[start] <= 300) end++;
    if (end === start) end++;
    const p = pts.slice(start, end + 1), t = times.slice(start, end + 1);
    let m = 0;
    for (let i = 1; i < p.length; i++) m += dist(p[i - 1], p[i]);
    chunks.push({ seq: seq++, from: t[0], to: t.at(-1), polyline: encode(p), offsets: t.map((x) => x - t[0]), acc: p.map((_, i) => 6 + ((i * 5) % 9)), m: Math.round(m) });
    start = end;
  }
}

